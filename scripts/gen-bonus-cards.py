import json, re, sys
"""Regenerate src/lib/data/bonusCards.ts.

Usage: git clone --depth 1 https://github.com/navarog/wingsearch /tmp/ws
       python3 scripts/gen-bonus-cards.py /tmp/ws src/lib/data/bonusCards.ts
"""
src, out = sys.argv[1], sys.argv[2]
b = json.load(open(f'{src}/src/assets/data/bonus.json'))
de = json.load(open(f'{src}/src/assets/data/i18n/de.json'))['bonuses']
def clean(s):
    if not s: return None
    s = re.sub(r'\s+', ' ', s.replace(' ', ' ')).strip()
    return s
cards = []
for x in sorted(b, key=lambda x: x['id']):
    name = x['Bonus card'] or ''
    if name.startswith('[') : continue  # fan made / automa-only
    t = de.get(str(x['id']), {})
    cards.append({
        'id': x['id'],
        'set': x['Set'],
        'automa': x['Automa'] == 'X',
        'name': {'en': clean(name), 'de': clean(t.get('Name'))},
        'condition': {'en': clean(x['Condition']), 'de': clean(t.get('Condition'))},
        'vp': {'en': clean(x['VP']), 'de': clean(t.get('VP'))},
    })
body = ',\n'.join('    ' + json.dumps(c, ensure_ascii=False) for c in cards)
open(out, 'w').write(f'''/**
 * Wingspan bonus cards (English and German / Feuerland editions).
 *
 * GENERATED by scripts/gen-bonus-cards.py – do not edit by hand. Source: the community card
 * database of "wingsearch" (https://github.com/navarog/wingsearch, GPL-3.0),
 * reduced to card names, set, Automa compatibility, condition and scoring.
 * Fan-made and Automa-only cards are excluded. Icons are kept as tokens like
 * `[forest]` and rendered by the UI. `de: null` = no German text known yet
 * (e.g. the Americas expansion), the UI falls back to English.
 */
import type {{ BonusCard }} from './types';

export const BONUS_CARDS: readonly BonusCard[] = [
{body},
];
''')
print(len(cards), 'cards')
